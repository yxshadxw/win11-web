const { chromium } = require('playwright');
const base = process.argv[2] || 'http://localhost:3100';
const sq = (n) => (8 - Number(n[1])) * 8 + 'abcdefgh'.indexOf(n[0]);
(async () => {
  const b = await chromium.launch();
  const errs = [];
  const A = await (await b.newContext()).newPage(); const B = await (await b.newContext()).newPage();
  for (const [n, p] of [['A', A], ['B', B]]) p.on('pageerror', (e) => errs.push(n + ': ' + e.message));
  await A.goto(base + '/apps/chess/'); await A.selectOption('#mode', 'online'); await A.click('#create-room');
  await A.waitForSelector('#online-room:not([hidden])');
  const code = await A.textContent('#room-code'); console.log('room', code, '|', await A.textContent('#status'));
  await B.goto(base + '/apps/chess/?room=' + code); await B.waitForSelector('#online-room:not([hidden])');
  await A.waitForFunction(() => document.querySelector('#status').textContent.includes('내 차례'));
  console.log('A:', await A.textContent('#status'), '| B:', await B.textContent('#status'));
  const move = async (p, from, to) => { await p.click(`[data-square="${sq(from)}"]`); await p.click(`[data-square="${sq(to)}"]`); };
  const waitNotes = (p, n) => p.waitForFunction((n) => [...document.querySelectorAll('#moves li')].map((li) => li.textContent).join(' ').split(/\s+/).filter(Boolean).length >= n, n, { timeout: 8000 });
  // B (black) tries to move out of turn: must be ignored
  await move(B, 'e7', 'e5'); await B.waitForTimeout(400);
  console.log('B out-of-turn ignored:', (await B.$$('#moves li')).length === 0);
  await move(A, 'f2', 'f3'); await A.waitForTimeout(1500); console.log('after f3 A moves:', JSON.stringify(await A.textContent('#moves')), 'A err:', await A.textContent('#online-error'), '| B moves:', JSON.stringify(await B.textContent('#moves')), 'B status:', await B.textContent('#status')); await waitNotes(B, 1);
  await move(B, 'e7', 'e5'); await B.waitForTimeout(1500); console.log('B sel/err:', await B.textContent('#online-error'), '| B status:', await B.textContent('#status'), '| A moves:', JSON.stringify(await A.textContent('#moves'))); await waitNotes(A, 2);
  A.on('request', r => { if (r.url().includes('/api/chess/move')) console.log('A POST', r.postData()); });
  console.log('A before g4:', await A.textContent('#status'), 'sel', await A.evaluate(() => document.querySelector('.selected')?.dataset.square));
  await move(A, 'g2', 'g4'); await A.waitForTimeout(1500); console.log('A after g4:', await A.textContent('#status'), 'err', await A.textContent('#online-error'), 'sel', await A.evaluate(() => document.querySelector('.selected')?.dataset.square)); await waitNotes(B, 3);
  await move(B, 'd8', 'h4'); await waitNotes(A, 4);
  await A.waitForFunction(() => document.querySelector('#status').textContent.includes('체크메이트'));
  console.log('A:', await A.textContent('#status'), '| B:', await B.textContent('#status'));
  console.log('A moves:', (await A.textContent('#moves')).replace(/\s+/g, ' '));
  console.log('B board flipped (a8 bottom-right?):', await B.evaluate(() => document.querySelector('#board').lastElementChild.dataset.square === '0'));
  await B.screenshot({ path: 'tests/screenshots/chess-online-b.png' });
  await A.click('#restart'); await B.waitForFunction(() => document.querySelector('#rematch-note').textContent.includes('원합니다'));
  await B.click('#restart');
  await A.waitForFunction(() => document.querySelector('#room-role').textContent.includes('흑'));
  await B.waitForFunction(() => document.querySelector('#room-role').textContent.includes('백'), null, { timeout: 5000 }).catch(() => console.log('B never became white'));
  await B.waitForTimeout(300);
  console.log('B status after rematch:', await B.textContent('#status'), '| flipped:', await B.evaluate(() => document.querySelector('#board').lastElementChild.dataset.square === '0'));
  console.log('after rematch A:', await A.textContent('#room-role'), '| B:', await B.textContent('#room-role'), '| moves:', (await A.$$('#moves li')).length);
  console.log('errors:', errs);
  await b.close();
})();
